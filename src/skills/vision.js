// «Что на экране», «что тут написано», «подскажи, что делать в этой игре», «что это за ошибка» — Орион
// смотрит на экран (снимок видит только встроенная модель на этом компьютере) и отвечает. Если для хорошего
// ответа нужен интернет (прохождение, решение ошибки), модель называет запрос — Орион ищет и пересказывает;
// в сеть уходит только этот запрос, а не снимок.

// Фразы без модели: явно про экран, игру на экране или ошибку на экране
const QUICK = [
  /^(?:а )?(?:что|чё|че) (?:у меня |сейчас )?(?:на экране|на мониторе|на рабочем столе)$/,
  /^(?:посмотри|глянь|взгляни) на (?:экран|монитор)/,
  /^что (?:тут|здесь|там|на экране) (?:написано|за надпись|пишут)/,
  /^(?:что ты видишь|что видишь|ты видишь экран)$/,
  /^(?:подскажи|помоги|посоветуй)(?: мне)? .*(?:в (?:этой )?игре|с (?:этой )?игрой|на экране|с этим окном|с этой ошибкой|с этим уровнем)/,
  /^как (?:пройти|победить|убить|решить) (?:этот|это|эту|этого|данный) /,
  // Игра на экране: «как пройти этот уровень», «как победить этого босса», «подскажи с этой головоломкой»
  /(?:^|\s)(?:этот|этого|эту|этой|этом) (?:уровень|уровне|босс\S*|мисси\S*|квест\S*|загадк\S*|головоломк\S*|задани\S*)/,
  /^(?:что это за|что за) (?:ошибк|окно|программ|игр)\S*(?: на экране)?$/,
  /^(?:прочитай|переведи) (?:то )?(?:что )?(?:на экране|с экрана|тут написано)/,
];

function quick(text) {
  const t = String(text)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[?!.,;:«»"]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  if (!QUICK.some((re) => re.test(t))) return null;
  return { addressed: true, say: '', actions: [{ tool: 'look_screen', arg: String(text).trim() }] };
}

// Вопрос, на который может понадобиться интернет: как сделать, что делать, ошибка, игра. «Что на экране» — нет
const NEEDS_WEB =
  /как |почему|зачем|что делать|что значит|ошибк|пройти|победить|убить|совет|подскажи|помоги|уровень|босс|миссия|квест|сделать/i;

const system = (name, web) =>
  `Ты ${name}, голосовой ассистент. Тебе показан снимок экрана пользователя; в правом нижнем углу может быть ` +
  'панель самого ассистента — не обращай на неё внимания. Ответь на вопрос по-русски: 1–3 предложения, до 50 слов, ' +
  'конкретно по тому, что видно, — называй надписи, кнопки, числа. Не выдумывай: если надпись не читается — так и ' +
  'скажи. Не повторяйся и не перечисляй одинаковое. Если на экране игра и спрашивают совет — дай практичный совет ' +
  'по ситуации на экране. ' +
  (web
    ? 'Если ответа на экране нет и нужны сведения из интернета (прохождение, решение ошибки), добавь последней ' +
      'строкой: ПОИСК: короткий запрос. '
    : 'Интернет не нужен — отвечай только по снимку. ') +
  'Без markdown, ответ будет озвучен.';

// Зацикленная модель: ««Орион (Окно)», «Орион (Окно)», …» — оставить одно и оборвать перечисление
const unloop = (text) =>
  String(text)
    .replace(/(.{4,80}?)(?:[,;]?\s*\1){2,}/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();

// Ответ модели → { say, query }: строка «ПОИСК: …» — запрос в интернет
function parseAnswer(text) {
  const raw = String(text || '').trim();
  const m = raw.match(/(?:^|\n)\s*ПОИСК:\s*(.+?)\s*$/i);
  const say = unloop((m ? raw.slice(0, m.index) : raw).replace(/\*\*|__|#+\s/g, ''));
  return { say, query: m ? m[1].replace(/[«»"]/g, '').trim().slice(0, 120) : '' };
}

async function lookScreen(question, ctx) {
  const vision = ctx.vision;
  const s = vision?.status();
  if (!s) return { ok: false, message: 'Смотреть на экран я пока не умею, сэр.' };
  if (ctx.config.backend === 'none')
    return {
      ok: false,
      message: 'Чтобы смотреть на экран, нужна большая модель Qwen 3.5 на этом компьютере — её можно скачать в настройках.',
    };
  if (!s.local)
    return {
      ok: false,
      message: 'Смотреть на экран я умею только со встроенной моделью на этом компьютере: снимок экрана не должен уходить в интернет.',
    };
  if (!s.supported)
    return { ok: false, message: 'У выбранной модели нет зрения. Видит экран Qwen 3.5 4B — её можно выбрать в настройках.' };
  if (s.installing) return { ok: true, speak: 'Модуль зрения ещё скачивается, сэр. Скажу, когда закончу.' };
  if (!s.installed) {
    const mb = Math.round((s.size || 6.7e8) / 1e6);
    if (!(await ctx.confirm(`Чтобы видеть экран, нужно один раз скачать модуль зрения — ${mb} МБ. Скачать?`)))
      return { ok: false, message: 'Хорошо, без зрения, сэр.' };
    vision
      .install()
      .then(() => ctx.remind('Модуль зрения готов. Спросите «что на экране» — посмотрю.'))
      .catch((err) => ctx.remind(`Модуль зрения не скачался: ${String(err?.message || err).slice(0, 80)}.`));
    return { ok: true, speak: 'Скачиваю модуль зрения, это пара минут. Скажу, когда закончу.' };
  }
  const image = await vision.capture();
  const asked = String(question || 'Что на экране?');
  const web = NEEDS_WEB.test(asked);
  const answer = parseAnswer(await vision.ask(image, asked, system(ctx.config.name, web)));
  if (!web) answer.query = ''; // «что на экране» — без интернета, даже если модель попросила
  ctx.audit({ vision: question, query: answer.query || undefined });
  if (!answer.query) return { ok: true, speak: answer.say || 'Не разобрал, что на экране, сэр.' };
  // Нужен интернет: ищем названный запрос и добавляем найденное к тому, что видно
  const found = await ctx.call('web_search', answer.query).catch(() => null);
  const extra = found?.ok && found.speak ? ` ${found.speak}` : '';
  return { ok: true, speak: `${answer.say}${extra}`.trim(), sources: found?.sources };
}

