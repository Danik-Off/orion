const byCode = new Map(UNITS.map((u) => [u[0], u]));

// Температура — не множитель: через Цельсий
const toC = { c: (v) => v, f: (v) => ((v - 32) * 5) / 9, k: (v) => v - 273.15 };
const fromC = { c: (v) => v, f: (v) => (v * 9) / 5 + 32, k: (v) => v + 273.15 };

// Число — с разумной точностью: 8,047 км, 37,8 °C, 0,000621 мили
function shown(v) {
  if (v === 0) return '0';
  const a = Math.abs(v);
  const digits = a >= 100 ? 1 : a >= 1 ? 3 : Math.min(6, 2 - Math.floor(Math.log10(a)));
  return money(Number(v.toFixed(digits)), digits);
}
// «5 километров», «2,5 километра» (дробное — родительный единственного), «1 километр»
function counted(v, [one, few, many]) {
  const r = Number(v.toFixed(6));
  return `${shown(v)} ${Number.isInteger(r) ? plural(Math.abs(r), one, few, many) : few}`;
}

function convert(arg) {
  const m = String(arg).match(/^\s*(-?\d+(?:[.,]\d+)?)?\s*([a-z0-9]+)\s*>\s*([a-z0-9]+)\s*$/i);
  if (!m) return { ok: false, message: 'Не понял, что во что перевести, сэр.' };
  const value = m[1] === undefined ? 1 : Number(m[1].replace(',', '.'));
  const from = byCode.get(m[2].toLowerCase());
  const to = byCode.get(m[3].toLowerCase());
  if (!from || !to) return { ok: false, message: 'Таких единиц я не знаю, сэр.' };
  if (from[1] !== to[1]) return { ok: false, message: `Нельзя перевести ${from[4][2]} в ${to[4][2]}, сэр: это разные величины.` };
  const result = from[1] === 'temp' ? fromC[to[0]](toC[from[0]](value)) : (value * from[2]) / to[2];
  return { ok: true, speak: `${counted(value, from[4])} — это ${counted(result, to[4])}.` };
}

// Слово → код единицы. Скорость и температуру из нескольких слов склеивает prepare
const unitOf = (word) => UNITS.find(([, , , re]) => re.test(word))?.[0] || null;
function prepare(text) {
  return String(text)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/(\d)[.,](?=\d)/g, '$1.')
    .replace(/[?!,;:«»"]+/g, ' ')
    .replace(/километр\S* в час|км ?\/ ?ч|км в час/g, 'кмч')
    .replace(/метр\S* в секунду|м ?\/ ?с(?=\s|$)/g, 'мс')
    .replace(/мил\S* в час/g, 'мильч')
    .replace(/(?:градус\S* )?(?:по )?(цельси|фаренгейт|кельвин)\S*/g, '$1')
    .replace(/(?:^|\s)градус\S*(?=\s|$)/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
const numberOf = (s) => {
  if (!s) return null;
  if (/^-?\d+(?:\.\d+)?$/.test(s)) return Number(s);
  if (/^полтор/.test(s)) return 1.5;
  return wordsToNumber(s);
};
// Слова перед единицей — число: «пять», «двадцать пять», «5», «2.5», «полтора», «минус сорок».
// Берём самую длинную цепочку слов-чисел прямо перед единицей («будет 2.5» — это 2.5, а не 2)
const isNumberWord = (w) => /^-?\d+(?:\.\d+)?$/.test(w) || /^полтор/.test(w) || (!/\d/.test(w) && wordsToNumber(w) !== null);
function numberBefore(words, i) {
  let k = i;
  while (k > 0 && i - k < 3 && isNumberWord(words[k - 1])) k -= 1;
  if (k === i) return null;
  const n = numberOf(words.slice(k, i).join(' '));
  if (n === null || n === undefined) return null;
  return words[k - 1] === 'минус' ? -n : n;
}

// «сколько будет 5 миль в километрах», «переведи 100 фаренгейт в цельсий», «10 кг это сколько фунтов»,
// «сколько сантиметров в дюйме», «сколько секунд в сутках» → plan convert
function quick(text) {
  const t = prepare(text);
  if (!/(?:^|\s)(?:в|во|это сколько)(?:\s|$)|^сколько/.test(t)) return null;
  const words = t.split(' ');
  const found = words.map((w, i) => [unitOf(w), i]).filter(([u]) => u);
  if (found.length !== 2) return null;
  const [[u1, i1], [u2, i2]] = found;
  if (byCode.get(u1)[1] !== byCode.get(u2)[1]) return null; // «5 минут в часах» — да, «рублей в метрах» — нет
  // Между единицами — «в» или «это сколько»: «сколько дней до нового года» — не перевод лет в дни
  const between = words.slice(i1 + 1, i2);
  if (!between.some((w) => w === 'в' || w === 'во' || w === 'сколько')) return null;
  const plan = (arg) => ({ addressed: true, say: '', actions: [{ tool: 'convert', arg }] });
  const n1 = numberBefore(words, i1);
  const n2 = numberBefore(words, i2);
  // «сколько сантиметров в (одном) дюйме» — второе переводим в первое
  if (/^сколько/.test(t) && n1 === null && words[i2 - 1] !== 'будет') return plan(`${n2 ?? 1} ${u2}>${u1}`);
  if (n1 === null && n2 === null) return null;
  return plan(`${n1 ?? 1} ${u1}>${u2}`);
}

