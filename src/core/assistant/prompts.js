function contextPrompt({ query, person, mem, shared, details }) {
  const who = person?.id
    ? `Собеседник: ${person.name || 'владелец голоса (имя пока неизвестно — можно спросить)'}; обращение: ${person.honorific || 'сэр'}.`
    : 'Собеседник: гость — голос не узнан, обращение: без обращения. Личное о нём не запоминай.';
  const facts = mem.factsText(query);
  const place = shared.profile().city;
  const common = shared.factsText(query).replace(/^#/gm, '#о'); // общие факты — с префиксом «о»
  return `Сейчас: ${new Date().toLocaleString('ru-RU', { dateStyle: 'full', timeStyle: 'short' })}.
${who}
Профиль собеседника: ${mem.profileText() || '(пусто)'}
Что ты знаешь о собеседнике (номер и факт):
${facts || '(пока ничего)'}
Общая память (не о конкретном человеке): ${place ? `ты находишься в городе ${place}.` : 'где ты находишься — неизвестно.'}
${common || '(общих фактов пока нет)'}
${details === null ? '' : `\nИнструменты для этой фразы:\n${details || '(не нужны — просто ответь)'}`}`;
}

// Данные для узкого промпта — только те, что навык объявил в needs (core/skills.js)
const CONTEXT = {
  now: () => `Сейчас: ${new Date().toLocaleString('ru-RU', { dateStyle: 'full', timeStyle: 'short' })}.`,
  person: ({ person, mem }) =>
    person?.id
      ? `Собеседник: ${person.name || mem.profile?.().name || 'имя неизвестно'}; обращение: ${person.honorific || 'сэр'}.`
      : 'Собеседник: гость (голос не узнан); без обращения.',
  city: ({ shared, mem }) => {
    const city = mem.profile?.().city || shared.profile().city;
    return city ? `Город: ${city}.` : 'Город неизвестен.';
  },
  facts: ({ query, mem, shared }) =>
    [
      `Что известно о собеседнике (номер и факт):\n${mem.factsText(query) || '(ничего)'}`,
      `Общая память:\n${shared.factsText(query).replace(/^#/gm, '#о') || '(ничего)'}`,
    ].join('\n'),
};

// Узкий промпт: одна задача одного навыка — его инструменты, правила, примеры и нужные ему данные.
// Короче полного в несколько раз: модель отвечает быстрее и не отвлекается на чужие навыки
function focusedPrompt({ name, skill, tool, details, query, person, mem, shared }) {
  const needs = skill.needs || ['now'];
  const data = needs
    .filter((k) => CONTEXT[k])
    .map((k) => CONTEXT[k]({ query, person, mem, shared }))
    .join('\n');
  return `Ты — ${name}, голосовой ассистент. Язык — русский.
Просьбу человека нужно выполнить инструментом навыка «${skill.title || skill.id}»${tool ? ` — скорее всего, ${tool}` : ''}.
Ответ — ровно один JSON-объект: {"topic": "${skill.id}", "actions": [{"tool": "...", "arg": "..."}], "say": "..."}.
Аргумент пиши строго в формате, описанном у инструмента. Числа — цифрами. "say" — короткая фраза для озвучки (1 предложение).
Названия программ, игр, песен, городов — как их сказал человек: не переводи и не пиши латиницей, если формат не требует иного.
Если просьба на самом деле не для этого навыка — actions пустой, say пустой.

Инструменты:
${details}

Данные:
${data || '(не нужны)'}`;
}

// systemPrompt(query, person, mem, skillIds) — каталог навыков стабилен, подробности — только выбранных
// dispatch(query, person, mem) — диспетчер двухшагового разбора; focused({ skillId, tool, query, person, mem }) — узкий промпт
function createPrompts({ name, skills, memory }) {
  // Неизменная часть собирается заново, только если каталог навыков изменился (init навыка дополнил описание)
  let cached = { catalog: null, text: '' };
  const head = () => {
    const catalog = skills.catalogPrompt();
    if (catalog !== cached.catalog) cached = { catalog, text: staticPrompt(name, catalog) };
    return cached.text;
  };
  const systemPrompt = (query, person, mem, skillIds) =>
    `${head()}\n\n${contextPrompt({ query, person, mem, shared: memory.shared, details: skills.detailsPrompt(skillIds) })}`;
  let dispatchCached = { tools: null, text: '' };
  const dispatchHead = () => {
    const tools = skills.toolCatalogPrompt();
    if (tools !== dispatchCached.tools) dispatchCached = { tools, text: dispatchStaticPrompt(name, tools) };
    return dispatchCached.text;
  };
  // Диспетчер: каталог инструментов (неизменный, кэшируется) + данные о собеседнике + правила и примеры навыков,
  // которые слова фразы называют («кто такой …» — поиск, «меня зовут …» — профиль, названия установленных игр).
  // Без них маленькая модель отвечала по памяти вместо инструмента. Форматов аргументов здесь нет — они во втором шаге
  const dispatch = (query, person, mem, skillIds = []) => {
    const hints = [skills.rulesPrompt(skillIds), skills.examplesPrompt(skillIds)].filter(Boolean).join('\n');
    const context = contextPrompt({ query, person, mem, shared: memory.shared, details: null });
    return `${dispatchHead()}\n\n${context}${hints ? `\nПравила и примеры навыков, подходящих к этой фразе:\n${hints}` : ''}`;
  };
  const focused = ({ skillId, tool, query, person, mem }) =>
    focusedPrompt({
      name,
      skill: skills.skillInfo(skillId),
      tool,
      details: skills.detailsPrompt([skillId]),
      query,
      person,
      mem,
      shared: memory.shared,
    });
  return { systemPrompt, dispatch, focused };
}

module.exports = { createPrompts };
