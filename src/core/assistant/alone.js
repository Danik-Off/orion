// Ступень «без большой модели»: её нет (не скачана, выключена), а быстрый разбор и маленькая модель фразу
// не взяли. Вместо «нужна большая модель» — то, что можно сделать правилами, урезанно:
//   • несколько дел в одной фразе («закрой хром и поставь громкость на 30») — по частям, каждая своим разбором;
//   • навык по словам фразы («что завтра в Питере с погодой») — аргумент по правилам (lib/text-args.js);
//   • вопрос о мире («кто такой…», «в каком году…») — поиск в интернете, ответ — выдержкой из найденного;
//   • простой разговор («как дела», «спасибо») — короткие готовые ответы;
//   • обрывок распознавания («закипёж») — переспросить.
// Ничего не подошло — null: следующая ступень скажет, что для этого нужна большая модель.
const { fromText } = require('../../lib/text-args');
const { normalizeRequest } = require('../../lib/idioms');
const { chatPlan } = require('./plan');
const { routable } = require('../router');

// Разделители дел: «и», «потом», «а ещё» перед глаголом-командой (как MULTI в core/router.js)
const SPLIT =
  /\s*,?\s+(?:и|а потом|потом|затем|после этого|а ещё|а еще)\s+(?=(?:мне\s+)?(?:включи|выключи|открой|закрой|запусти|поставь|найди|покажи|напомни|сделай|скажи|какая|какой|какие|сколько|что|убавь|прибавь|переключи)(?:\s|$))/iu;
// Глагол-команда в начале — человек о чём-то просит
const COMMAND =
  /^(?:включи|выключи|отключи|открой|закрой|запусти|поставь|сделай|найди|покажи|напомни|расскажи|скажи|убери|добавь|запиши|разбуди|переведи|посчитай|узнай|останови|прибавь|убавь|переключи|перезагрузи|засеки|сверни|удали|вычеркни|прочитай|проверь|верни|смени|поменяй|отмени|заблокируй|напечатай)(?:\s|$)/;
const QUESTION =
  /^((?:объясни|расскажи)(?: мне)?(?: простыми словами)?,? (?:что так(?:ое|ая)|как работает|почему|зачем)|в ч[её]м разница|как правильно|что значит|что означает|кто (такой|такая|такие|был|была|выиграл|написал|изобрел|открыл|сейчас)|что так(ое|ая)|когда (был|была|было|будет|вышел|вышла|родился)|в каком году|где (находится|живет)|сколько (сейчас |в среднем )?(лет|стоит|стоят|весит|людей|человек|км|километров|живет)|почему|зачем|какая столица|какой самый|как называется|как работает)/u;
const TALK = [
  [/^(?:привет|здравствуй|здравствуйте|добрый (?:день|вечер)|доброй ночи|хай)(?: \S+)?$/, 'Здравствуйте, сэр.'],
  [/^(?:как (?:дела|ты|поживаешь|настроение)|как у тебя дела)(?: \S+)?$/, 'Всё в порядке, сэр. Чем помочь?'],
  [/^(?:(?:ну |ладно |ок )?(?:пока|до свидания|до встречи|спокойной ночи|всего доброго))$|^спасибо,? на сегодня все$/, 'До встречи, сэр.'],
  [/^(?:спасибо|благодарю|ты молодец|молодец|умница)(?: .*)?$/, 'Всегда рад, сэр.'],
  [
    /^(?:а )?(?:кто ты|ты кто|что ты такое)(?: такой| вообще| вообще такой| такая)?$|^кто ты вообще такой$|^как (?:тебя зовут|твое имя)$/,
    (name) => `Я ${name}, ваш голосовой помощник.`,
  ],
  [/^(?:алло )?(?:ты здесь|ты тут|ты меня слышишь|слышишь меня|ты где)$/, 'Да, слушаю, сэр.'],
  [
    /^(?:а )?(?:что ты (?:умеешь|можешь)|что умеешь)(?: делать)?$|^помоги(?: мне)?$|^помощь$/,
    'Без большой модели я выполняю команды: погода, музыка и радио, таймеры и будильник, заметки, громкость, программы, новости и поиск в интернете. Для разговора нужна большая модель — её можно скачать в настройках.',
  ],
];
// Продолжения после ответа навыка: «а завтра?» после погоды, «а другую» после радио, «ещё один на 10» после
// таймера, «а про спорт» после новостей. recent — навык прошлой реплики; → полная команда для обычного разбора
const minutesIfBare = (x) => (/\d+$|^[а-я]+$/.test(x) && !/минут|час|секунд/.test(x) ? `${x} минут` : x);
const CONTINUE = {
  weather: [
    [
      /^(?:а|и) ((?:завтра|послезавтра|сегодня|на выходн\S*|в выходн\S*|на неделю|на этой неделе|через \S+(?: \S+)?|в \S+)(?: .*)?)$/,
      (x) => `погода ${x}`,
    ],
  ],
  radio: [[/^(?:а |и )?(?:другую|другое|следующую|следующее|еще одну|ещё одну)(?: станцию| радио)?$/, () => 'включи другое радио']],
  reminders: [
    [
      /^(?:а |и )?(?:еще|ещё) (?:один |одно |одну )?(?:таймер |напоминание )?(?:на|через) (.+)$/,
      (x) => `поставь таймер на ${minutesIfBare(x)}`,
    ],
  ],
  news: [[/^(?:а|и) (?:про|о|об|что про|что с|что в) (.+)$/, (x) => `новости про ${x}`]],
};
function continuation(recent, t) {
  for (const [re, make] of CONTINUE[recent] || []) {
    const m = t.match(re);
    if (m) return make(m[1]);
  }
  return null;
}

// «Расскажи анекдот», «мне скучно» — анекдот без большой модели не придумать, а интересный факт — можно
const BORED = /анекдот|шутк|пошути|мне скучно|расскажи что(?:-| )нибудь$|развлеки/;

const clean = (t) =>
  String(t || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[?!.,;:«»"]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

// planPart(text) → план одной задачи или null: быстрый разбор → маленькая модель → навык по словам
function createAlone({ config, skills, router, planAlone }) {
  // Навык по словам фразы: первый его инструмент, чей аргумент разбирается правилами
  function bySkillWords(text) {
    // «закрой/выключи <программу>», которую слова навыков не называют («выруби дедлок»)
    const app = /^(?:закрой|выключи) (?!свет|компьютер|комп|радио|музыку|звук|экран|блютуз|вай|wi|будильник|таймер)/.test(clean(text));
    for (const { id } of skills.scores(text).filter((x) => x.words >= 1)) {
      for (const tool of skills.names().filter((n) => skills.skillOf(n) === id)) {
        const arg = fromText(tool, text, { config });
        if (typeof arg === 'string' && skills.argAllowed(tool, arg)) {
          const say = skills.speaksOf(tool) ? '' : 'Готово, сэр.';
          return { addressed: true, topic: id, actions: [{ tool, arg }], say, alone: true };
        }
      }
    }
    if (app) {
      const arg = fromText('close_app', text, { config });
      if (typeof arg === 'string' && arg)
        return { addressed: true, topic: 'apps', actions: [{ tool: 'close_app', arg }], say: '', alone: true };
    }
    return null;
  }

  async function planPart(raw) {
    const quick = skills.quickPlan(raw);
    // Дальше — фраза, приведённая к команде: «а можешь включить музыку» → «включи музыку»
    const text = normalizeRequest(raw) || raw;
    if (quick?.actions?.length) return quick;
    const r = router ? await router.route(text) : null;
    if (r?.plan) return r.plan;
    if (r?.focus) {
      const p = planAlone(r.focus, text);
      if (p) return p;
    }
    return bySkillWords(text);
  }

  async function plan(turn) {
    const text = turn.text;
    const t = clean(text);
    // «Закрой его», «и выключи его через час» — про то, что было раньше: без модели не понять, правилами не трогаем
    const refers = !routable(normalizeRequest(text) || text) && !SPLIT.test(text);
    // «Закрой его», «закрой это» — без модели не знаем, о чём речь раньше, но обычно это окно, которое впереди
    if (/^(?:закрой|выключи) (?:его|ее|это)$/.test(t) && skills.toolInfo('close_app'))
      return { addressed: true, topic: 'apps', actions: [{ tool: 'close_app', arg: 'его' }], say: '', alone: true };
    // Описание сценария («когда я говорю „я дома“ — включи джаз») — его без большой модели не записать честно
    if (/^когда (?:я )?(?:говорю|скажу)/.test(t))
      return chatPlan('Сценарии я записываю только с большой моделью, сэр. Её можно скачать в настройках.');
    // Уточнение к прошлому ответу без большой модели: «а завтра?» после погоды, «а другую» после радио…
    const next = continuation(turn.recent?.[0], t);
    if (next) {
      const p = await planPart(next);
      if (p?.actions?.length) return p;
    }
    // Несколько дел — по частям; все части должны разобраться, иначе лучше честно сказать, что не могу.
    // «Когда я говорю „я дома“ — включи джаз и скажи погоду» — это описание сценария, а не два дела
    const parts = /^когда (я )?(говорю|скажу)/.test(t)
      ? [text]
      : text
          .split(SPLIT)
          .map((p) => p.trim())
          .filter(Boolean);
    if (parts.length > 1 && parts.length <= 4 && parts.every((p) => routable(p))) {
      const plans = [];
      for (const part of parts) plans.push(await planPart(part));
      const done = plans.filter((p) => p?.actions?.length);
      // Что разобралось — выполнить; что нет — назвать (целую фразу правилами не трогаем: «телеграм, потом
      // включи музыку» стало бы названием программы)
      if (done.length) {
        const actions = done.flatMap((p) => p.actions);
        const missed = parts.filter((_, i) => !plans[i]?.actions?.length);
        const tail = missed.length ? `А «${missed.join('», «')}» без большой модели не понял, сэр.` : '';
        const quiet = actions.every((a) => skills.speaksOf(a.tool));
        return { addressed: true, topic: done[0].topic, actions, say: tail || (quiet ? '' : 'Готово, сэр.'), alone: true };
      }
      return chatPlan('Без большой модели я выполняю команды по одной, сэр. Скажите их по очереди.');
    }
    if (!refers) {
      const own = bySkillWords(normalizeRequest(text) || text);
      if (own) return own;
    }
    // Вопрос о мире — поиск (навык поиска отвечает выдержкой из найденного: llm.answer без модели)
    if (QUESTION.test(t) && skills.toolInfo('web_search')) {
      return { addressed: true, topic: 'search', actions: [{ tool: 'web_search', arg: text.trim() }], say: '', alone: true };
    }
    if (BORED.test(t) && skills.toolInfo('fact'))
      return {
        addressed: true,
        topic: 'facts',
        actions: [{ tool: 'fact', arg: '' }],
        say: 'Анекдоты я придумываю только с большой моделью, а вот интересный факт.',
        alone: true,
      };
    for (const [re, answer] of TALK) {
      if (re.test(t)) return chatPlan(typeof answer === 'function' ? answer(config.name) : answer);
    }
    // Продолжение разговора без имени, ничего не подошло и это не просьба (нет глагола-команды) — скорее всего,
    // сказано не Ориону: промолчать. Просьбу («открой настройки») молча не бросаем — ответит следующая ступень
    if (turn.source?.startsWith('followup') && !COMMAND.test(normalizeRequest(text) || t))
      return { addressed: false, topic: 'chat', actions: [], say: '' };
    // «Давай», «ну», «да» с именем — ждёт продолжения
    if (/^(давай|ну|да|ага|слушай|эй|так|алло)$/.test(t)) return chatPlan('Слушаю, сэр.');
    // Остальное без большой модели не понять: следующая ступень так и скажет (а не «не расслышал»)
    return null;
  }

  return { plan, planPart };
}

module.exports = { createAlone, SPLIT, QUESTION, continuation };
