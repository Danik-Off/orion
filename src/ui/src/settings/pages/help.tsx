// «Что я умею»: примеры того, что можно сказать, по темам. Нажатый пример сразу выполняется в окне разговора —
// так проще всего узнать возможности (главная жалоба на голосовых помощников — «не понимает», и часто
// просто потому, что человек не знает, как сказать). Все примеры понимаются и без большой модели.
