function Help({ ctx }: { ctx: Ctx }) {
  return (
    <>
      {GROUPS.map(([title, phrases]) => (
        <Section key={title} title={title}>
          <div className="help-phrases">
            {phrases.map((p) => (
              <Chip key={p} title="Нажмите — выполню в окне разговора" onClick={() => ctx.api.tryPhrase(p)}>
                {p}
              </Chip>
            ))}
          </div>
        </Section>
      ))}
      <p className="note help-note">
        Говорите своими словами: «а можешь включить музыку», «мне завтра вставать в шесть», «очень громко» — я пойму. Начинайте с имени или
        нажмите горячую клавишу. После ответа несколько секунд можно продолжать без имени.
      </p>
    </>
  );
}

export const help: Page = {
  id: 'help',
  group: 'assistant',
  title: 'Что я умею',
  icon: 'help',
  description: 'Примеры того, что можно сказать. Нажмите на пример — я сразу его выполню.',
  keywords: 'помощь справка команды примеры что сказать умеешь возможности',
  Render: Help,
};
