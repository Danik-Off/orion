// Имя ассистента: на него Орион откликается, его же слышит вся семья. Что не годится — и почему:
// оскорбления и брань («теперь тебя зовут …» сказали в шутку — а потом это слово в каждом ответе);
// обычные слова речи («алло», «да», «стоп») — на них он откликался бы посреди любого разговора;
// слишком короткое — распознаватель путает его с другими словами.
// nameProblem(имя) → текст отказа или null, если имя подходит.

// Основы: совпадение в начале слова — «негр», «негра», «пидорас»; ловит и формы, и составные
const OFFENSIVE =
  /^(?:негр|нигер|ниггер|пидор|пидар|педик|педераст|хуй|хуе|хуи|пизд|бляд|блят|бля|сук[аи]|мудак|мудил|долбо|дебил|идиот|урод|говн|жоп|чмо|лох|шлюх|жид|хохл|хохол|чурк|хач|даун|конч|еба|ёба|ебл|ёбл|тупиц|тупой|дура|дурак|придур|мраз|тварь|скотин|выблядок|гандон|гондон|залуп|манда|дрочи|фашист|нацист|гитлер)/i;
const COMMON = new Set([
  'алло',
  'да',
  'нет',
  'стоп',
  'привет',
  'пока',
  'ок',
  'окей',
  'ладно',
  'слушай',
  'эй',
  'давай',
  'включи',
  'выключи',
  'компьютер',
  'музыка',
  'погода',
  'время',
  'мама',
  'папа',
  'это',
  'вот',
  'так',
]);

function nameProblem(raw) {
  const name = String(raw || '').trim();
  if (!name) return 'Имя не может быть пустым.';
  if (!/^[А-ЯЁа-яёA-Za-z-]+$/.test(name)) return 'Имя — одно слово, только буквы.';
  if (name.replace(/-/g, '').length < 3) return 'Слишком короткое имя: я буду путать его с другими словами. Нужно хотя бы три буквы.';
  if (name.length > 20) return 'Слишком длинное имя — до двадцати букв.';
  const low = name.toLowerCase().replace(/ё/g, 'е');
  if (OFFENSIVE.test(low)) return 'Такое имя я не возьму: это грубое слово.';
  if (COMMON.has(low)) return `«${name}» — обычное слово: я откликался бы на него посреди любого разговора. Выберите имя.`;
  return null;
}

module.exports = { nameProblem };
