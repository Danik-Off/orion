// reorder: false — не переставлять глагол из конца («громко очень убавь» бытовые фразы понимают и так)
function normalizeRequest(text, { reorder = true } = {}) {
  let t = norm(text)
    .replace(/(^|\s)(?:вкл|вруби|врубай|включай|запускай)(?=\s|$)/g, '$1включи')
    .replace(/(^|\s)(?:выкл|выруби|вырубай|выключай|отрубай|отруби)(?=\s|$)/g, '$1выключи')
    .replace(/(^|\s)(\S+[иь]) ка(?=\s|$)/g, '$1$2') // «включи ка» → «включи»
    .replace(/\s+а то .+$/, '') // «включи радио маяк, а то скучно»
    .replace(/(^|\s)(?:это самое|короче|типа|как бы|значит|ну|э+|м+)(?=\s|$)/g, '$1') // «ну это самое музыку…»
    .replace(/^(что|какая|какой|какие|как|сколько) там /, '$1 ') // «какая там погода» — «там» тут не место
    .replace(/\s+/g, ' ')
    .trim();
  for (let i = 0; i < 4 && LEAD.test(t); i++) t = t.replace(LEAD, '');
  for (let i = 0; i < 3 && TAIL.test(t); i++) t = t.replace(TAIL, '');
  const wrap = t.match(WRAP);
  if (wrap) t = `${IMPERATIVE[wrap[1]]}${t.slice(wrap[0].length)}`;
  const late = t.match(new RegExp(`^(?:а )?(?:ты )?(?:можешь|сможешь|не мог бы|не могла бы|можно)(?: мне)? (.+) (${VERBS})$`));
  if (late) t = `${IMPERATIVE[late[2]]} ${late[1]}`;
  // «включи мне пожалуйста музыку» → «включи музыку»
  t = t.replace(new RegExp(`^(${COMMANDS}) (?:мне |нам )?(?:пожалуйста )?`), '$1 ');
  // «блютуз включи», «музыку выключи», «радио маяк включи» — глагол в конце
  const tail = t.match(new RegExp(`^(.{2,40}?) (${COMMANDS})$`));
  if (reorder && tail && !tail[1].includes(' не')) t = `${tail[2]} ${tail[1]}`;
  // «хочу музыку», «музыку давай», «радио маяк хочу»
  const want = t.match(/^(?:хочу|хочется|давай) (музыку|песню|песенку|радио.*|новости)$|^(музыку|песню|радио.*|новости) (?:хочу|давай)$/);
  if (want) t = (want[1] || want[2]) === 'новости' ? 'расскажи новости' : `включи ${want[1] || want[2]}`;
  for (const [re, make] of REWRITES) {
    const m = t.match(re);
    if (m) t = make(m);
  }
  return t.replace(/\s+/g, ' ').trim();
}

