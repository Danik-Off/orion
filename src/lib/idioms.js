// t — исходная фраза; ctx — контекст навыков (радио играет?); → план или null
function idiomPlan(text, ctx) {
  const forms = [...new Set([normalizeRequest(text, { reorder: false }), normalizeRequest(text)])];
  for (const t of forms) {
    for (const [re, make] of IDIOMS) {
      const m = t.match(re);
      const result = m ? make(t, ctx, m, String(text || '')) : null;
      if (result) return result; // правило подошло по словам, но не разобрало — пробуем следующие
    }
  }
  return null;
}

