// Падеж порядкового по предлогу перед ним: «в 1962 году» → prep, «к 2030 году» → dat, «с 12 апреля» → gen
function caseByPreposition(prev, fallback) {
  const p = (prev || '').toLowerCase();
  if (['в', 'во', 'о', 'об', 'при'].includes(p)) return 'prep';
  if (['к', 'ко'].includes(p)) return 'dat';
  if (['по', 'на', 'за', 'про', 'через'].includes(p)) return 'acc';
  if (GEN_PREPS.has(p)) return 'gen';
  return fallback;
}

