// «Липецк отмечает 323 года» — это счёт лет, а не 323-й год. Счёт — когда слово согласовано с числом
// как при счёте (1 год, 2–4 года) и либо перед числом слово счёта («отмечает», «исполнилось», «через»…),
// либо число меньше 1000 без предлога даты («в 323 году» — год). «321 год до н. э.» — всегда год.
const COUNT_BEFORE =
  /^(отмечает|отмечают|отметил|отметила|отметит|празднует|праздновал|исполнилось|исполняется|исполнится|прошло|пройдёт|пройдет|спустя|через|уже|почти|всего|целых|ровно|лишь|только|длилась|длился|длилось|продолжалась|продолжался|насчитывает|существует|существовал|существовала|живёт|живет|жил|жила)$/i;
