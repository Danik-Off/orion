function plural(n, [one, few, many]) {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

function triple(n, gender) {
  const out = [];
  if (n >= 100) out.push(HUNDREDS[Math.floor(n / 100)]);
  const rest = n % 100;
  if (rest >= 10 && rest < 20) out.push(TEENS[rest - 10]);
  else {
    if (rest >= 20) out.push(TENS[Math.floor(rest / 10)]);
    if (rest % 10) out.push(ONES[gender][rest % 10]);
  }
  return out;
}

// 1024 → «одна тысяча двадцать четыре»; gender — род того, что считаем (для 1 и 2)
function numberToWords(value, gender = 'm') {
  let n = Math.floor(Math.abs(value));
  if (n === 0) return 'ноль';
  if (n >= 1e12) return String(value); // такие числа вслух не нужны
  const words = [];
  const groups = [];
  while (n > 0) {
    groups.push(n % 1000);
    n = Math.floor(n / 1000);
  }
  for (let i = groups.length - 1; i >= 0; i--) {
    const g = groups[i];
    if (!g) continue;
    const scale = SCALES[i];
    words.push(...triple(g, scale ? scale.gender : gender));
    if (scale) words.push(plural(g, scale.forms));
  }
  // 1500 → «тысяча пятьсот»: так говорят, «одна тысяча» — только в документах
  if (words[0] === 'одна' && words[1] === 'тысяча') words.shift();
  return words.join(' ');
}

// Род существительного после числа: по окончанию слова в той форме, в какой оно уже стоит
// («1 минута» → ж.р., «2 минуты» → ж.р., «2 рубля» → м.р., «1 окно» → ср.р.)
function genderOf(noun, n) {
  if (!noun) return 'm';
  const w = noun.toLowerCase();
  const last = n % 10;
  const teen = n % 100 >= 11 && n % 100 <= 19;
  if (teen) return 'm';
  if (last === 1) {
    if (/[ая]$/.test(w) && !/^(папа|дядя|мужчина|судья)$/.test(w)) return 'f';
    if (/[ую]$/.test(w)) return 'fa'; // винительный: «одну минуту»
    if (/[оеё]$/.test(w) && !/^(кофе)$/.test(w)) return 'n';
    return 'm';
  }
  if (last === 2) return /[ыи]$/.test(w) ? 'f' : 'm';
  return 'm';
}

// Род после числа в родительном падеже: «около 1 минуты» → ж.р., «до 1 часа» → м.р.
function genderOfGenitive(noun, n) {
  if (!noun || n % 10 !== 1 || n % 100 === 11) return 'm';
  return /[ыи]$/.test(noun.toLowerCase()) ? 'f' : 'm';
}

const FRACTIONS = [null, ['десятая', 'десятых', 'десятых'], ['сотая', 'сотых', 'сотых'], ['тысячная', 'тысячных', 'тысячных']];

// 1,48 → «одна целая сорок восемь сотых»
function decimalToWords(intPart, fracPart) {
  const whole = Number(intPart);
  const frac = fracPart.slice(0, 3);
  const f = Number(frac);
  const wholeWords = `${numberToWords(whole, 'f')} ${plural(whole, ['целая', 'целых', 'целых'])}`;
  if (!f) return numberToWords(whole);
  return `${wholeWords} ${numberToWords(f, 'f')} ${plural(f, FRACTIONS[frac.length])}`;
}

