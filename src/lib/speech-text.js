function ordWord(k, gender, cs) {
  if (k === 3) return THIRD[gender][cs];
  if (gender === 'm' && (cs === 'nom' || cs === 'acc') && STRESSED_END.has(k)) return `${ORD[k]}ой`;
  return ORD[k] + ORD_ENDINGS[gender][cs];
}

// 1962, m, prep → «тысяча девятьсот шестьдесят втором»; 12, n, gen → «двенадцатого»
function ordinalWords(n, gender = 'm', cs = 'nom') {
  if (n <= 0 || n >= 1e6) return numberToWords(n);
  if (n % 1000 === 0 && ORD[n]) return ordWord(n, gender, cs);
  const low = n % 100;
  const hundreds = (n % 1000) - low;
  const thousands = n - (n % 1000);
  const parts = [];
  if (thousands) parts.push(numberToWords(thousands).replace(/^одна тысяча/, 'тысяча')); // в годах — «тысяча девятьсот…»
  if (!low) return [...parts, ordWord(hundreds, gender, cs)].join(' ');
  if (hundreds) parts.push(HUNDREDS[hundreds / 100]);
  if (low < 20 || low % 10 === 0) parts.push(ordWord(low, gender, cs));
  else parts.push(TENS[Math.floor(low / 10)], ordWord(low % 10, gender, cs));
  return parts.join(' ');
}

