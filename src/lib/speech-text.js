const ROMAN = { I: 1, V: 5, X: 10, L: 50, C: 100 };
function romanToInt(s) {
  let n = 0;
  for (let i = 0; i < s.length; i++) {
    const a = ROMAN[s[i]];
    const b = ROMAN[s[i + 1]] || 0;
    n += a < b ? -a : a;
  }
  return n;
}
function intToRoman(n) {
  let out = '';
  for (const [v, r] of [
    [100, 'C'],
    [90, 'XC'],
    [50, 'L'],
    [40, 'XL'],
    [10, 'X'],
    [9, 'IX'],
    [5, 'V'],
    [4, 'IV'],
    [1, 'I'],
  ]) {
    while (n >= v) ((out += r), (n -= v));
  }
  return out;
}
// Только правильно записанные числа до 100: «IIII», «VX» и случайные буквы не трогаем
const romanValue = (s) => {
  const n = romanToInt(s);
  return n > 0 && n < 100 && intToRoman(n) === s ? n : null;
};

// Падеж имени правителя по окончанию: «Пётр» — им., «Петра» — род. (и вин.), «Петру» — дат., «Петром» — твор., «Петре» — предл.;
// женские имена: «Екатерина» — им., «Екатерины» — род., «Екатерину» — вин., «Екатериной» — твор., «Екатерине» — дат.
const FEMALE_RULERS = /^(Екатерин|Елизавет|Анн|Мари|Ольг|Изабелл|Виктори|Елен|Софь|Софи|Маргарит|Кристин)/;
function rulerForm(name) {
  if (FEMALE_RULERS.test(name)) {
    if (/(ой|ей)$/.test(name)) return ['f', 'ins'];
    if (/[ыи]$/.test(name)) return ['f', 'gen'];
    if (/[ую]$/.test(name)) return ['f', 'acc'];
    if (/е$/.test(name)) return ['f', 'dat'];
    return ['f', 'nom'];
  }
  if (/(ом|ем|ём)$/.test(name)) return ['m', 'ins'];
  if (/[ая]$/.test(name)) return ['m', 'gen'];
  if (/[ую]$/.test(name)) return ['m', 'dat'];
  if (/е$/.test(name)) return ['m', 'prep'];
  return ['m', 'nom'];
}
