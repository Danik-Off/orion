function normalizeForSpeech(input) {
  // Символы и ссылки — первыми: «~5 минут» → «около 5 минут» (дальше родительный), «ya.ru» не попадёт под версии
  let t = normalizeSymbols(String(input));

  // «7 098 363» → «7098363», «1 234,56» → «1234,56» (но «5 100, 200» — это перечисление)
  t = t.replace(/(?<![\d.,])(\d{1,3})((?:[ \u00A0\u202F]\d{3})+)(?!\d|,(?!\d))/g, (m, a, b) => a + b.replace(/[ \u00A0\u202F]/g, ''));

  // Точка сокращения в конце предложения («…2 млрд.», «…3 шт.») — это и конец предложения:
  // удваиваем её, чтобы после раскрытия сокращения пауза перед следующей фразой не пропала
  t = t.replace(/(?<![\p{L}/])(тыс|млн|млрд|трлн|руб|коп|шт|ч|мин|сек|напр|др|пр|д|п)\.(?=\s*$|\s+[А-ЯЁA-Z])/gu, '$1..');

  // Сочетания букв и цифр, которые говорят словом: «3D», «5G», «CO2», «COVID-19»
  for (const [re, say] of MIXED) t = t.replace(re, say);

  // Версии и пункты: «Python 3.12», «USB 3.0», «версия 2.3.1», «пункт 3.2» → «три точка двенадцать»
  t = t.replace(
    /(?<=(?<![\p{L}\d])(?:[A-Za-z][A-Za-z\d-]*|версия|версии|версию|пункт|пункта|пункте|раздел|раздела|разделе|п\.|v)\s*)(\d+(?:\.\d+)+)(?![\d.,]\d)/giu,
    (m) =>
      m
        .split('.')
        .map((p) => (/^0\d/.test(p) ? 'ноль ' : '') + numberToWords(Number(p)))
        .join(' точка '),
  );

  // Римские цифры: века, правители, главы («Петра I» → «Петра Первого»)
  t = romanNumerals(t);

  // Разряды: «5 млн» → «5 миллионов», «1,5 млрд» → «полтора миллиарда», «$2 млрд» → «2 миллиарда долларов»,
  // «около 1 млн» → «около 1 миллиона» (дальше число согласуется обычными правилами ниже)
  t = t.replace(
    /(?:(\p{L}+)\s+)?(\$\s?)?(\d+(?:[.,]\d+)?)\s*(тыс|млн|млрд|трлн)\.?(?!\p{L})(?:\s*(₽|руб\.|\$|€|руб(?!\p{L})))?/gu,
    (m, prev, dollar, num, abbr, currency) => {
      const { forms, half } = ABBR_SCALES[abbr];
      const cur = currency ? ` ${CURRENCY_GEN[currency]}` : dollar ? ' долларов' : '';
      const lead = prev ? `${prev} ` : '';
      if (/[.,]/.test(num)) {
        const [a, b] = num.split(/[.,]/);
        if (a === '1' && /^50?$/.test(b) && !GENITIVE_BEFORE.test(prev || '')) return `${lead}${half} ${forms[1]}${cur}`;
        return `${lead}${num} ${forms[1]}${cur}`; // дробное: «2,3 миллиона»
      }
      const n = Number(num);
      const form = GENITIVE_BEFORE.test(prev || '') ? (n % 10 === 1 && n % 100 !== 11 ? forms[1] : forms[2]) : plural(n, forms);
      return `${lead}${num} ${form}${cur}`;
    },
  );

  // Числовые даты → «26 сентября 2026 года», дальше как обычная дата:
  // 26.09.2026, 26.09.2026 г., 26.09.26, 26/09/2026, 2026-09-26, а «26.09» без года — «26 сентября»
  const dateWords = (d, mo, y) => {
    const day = Number(d);
    const month = Number(mo);
    if (month < 1 || month > 12 || day < 1 || day > 31) return null;
    if (!y) return `${day} ${MONTHS[month - 1]}`;
    const year = y.length === 2 ? 2000 + Number(y) : Number(y);
    return `${day} ${MONTHS[month - 1]} ${year} года`;
  };
  const YEAR_SUFFIX = '(?:\\s*г\\.?(?!\\p{L})|\\s+года?(?!\\p{L}))?';
  t = t.replace(
    new RegExp(`(?<![\\d.,/])(\\d{4})-(\\d{2})-(\\d{2})(?![\\d-])${YEAR_SUFFIX}`, 'gu'),
    (m, y, mo, d) => dateWords(d, mo, y) || m,
  );
  t = t.replace(
    new RegExp(`(?<![\\d.,/])(\\d{1,2})([./])(\\d{1,2})\\2(\\d{4}|\\d{2})(?![\\d.,/]\\d)${YEAR_SUFFIX}`, 'gu'),
    (m, d, _sep, mo, y) => dateWords(d, mo, y) || m,
  );
  // «в 12.05», «с 9.30 до 18.00» — время через точку: дальше как «12:05»
  // Пара «с 9.00 до 18.30» — время, если хоть одна сторона не похожа на дату («с 1.10 по 5.10» — даты)
  const HHMM = '([01]?\\d|2[0-3])\\.([0-5]\\d)';
  t = t.replace(
    new RegExp(`(?<!\\p{L})(с|со|от)\\s+${HHMM}\\s*(до|[-–—])\\s*${HHMM}(?![\\d.,]\\d)`, 'giu'),
    (m, from, h1, m1, to, h2, m2) => ([m1, m2].every((x) => /^(0[1-9]|1[0-2])$/.test(x)) ? m : `${from} ${h1}:${m1} ${to} ${h2}:${m2}`),
  );
  t = t.replace(
    new RegExp(
      `(?<=(?<!\\p{L})(?:в|во|около|после)\\s+)${HHMM}(?![\\d.,]\\d|\\d|\\s*(?:[%°₽$€]|руб|коп|долл|евро|градус|процент|раз|тыс|млн|млрд|км|кг|[ГМКТ]Б))`,
      'giu',
    ),
    '$1:$2',
  );
  // «26.09» — дата, если месяц двузначный и дальше не единица («26.09 рубля» — это деньги)
  t = t.replace(
    /(?<![\d.,/:])(\d{1,2})\.(0[1-9]|1[0-2])(?![\d.,]\d|\d|\s*(?:[%°₽$€]|руб|коп|долл|евро|градус|процент|тыс|млн|млрд|трлн|утра|вечера|дня|ночи|час|мин|сек|раз|км|кг|м\/с|[ГМКТ]Б))/gu,
    (m, d, mo) => dateWords(d, mo) || m,
  );
  t = t.replace(/(?<![\d.,])\d+(?:\.\d+){2,}(?![\d.,]\d)/g, (m) =>
    m
      .split('.')
      .map((p) => numberToWords(Number(p)))
      .join(' точка '),
  ); // «2.3.1», IP-адрес

  // Десятилетия: «1990-х» → «девяностых», «1980-е» → «восьмидесятые», «2000-х» → «двухтысячных»
  t = t.replace(/(\d{3,4})-(х|е|ых|ые)(?!\p{L})/gu, (m, y, end) => {
    const n = Number(y);
    const k = n % 100 === 0 ? (n % 1000 === 0 ? n : n % 1000) : n % 100;
    if (!ORD[k] || n % 10 !== 0) return m;
    const stem = ORD[k] === 'сороков' ? 'сороков' : ORD[k];
    return `${stem}${/е/.test(end) ? 'ые' : 'ых'}`;
  });
  // «90-е годы», «в 90-х» — тоже десятилетия; «10-е место» — нет (дальше порядковое)
  t = t.replace(
    /(?<![\d.,])([2-9]0)-(е|х|ые|ых)(?=\s+год|\s*[^\s\p{L}]|\s*$)/gu,
    (m, y, end) => `${ORD[Number(y)]}${/е/.test(end) ? 'ые' : 'ых'}`,
  );

  // Порядковые с окончанием: «3-е издание», «на 2-м месте», «21-го века», «к 3-му числу», «5-х классов», «2-й»
  t = t.replace(
    /(?<![\d.,])(\d{1,4})-(ый|ий|ой|й|ая|я|ое|ее|е|ого|его|го|ому|ему|му|ым|им|ом|ем|м|ую|ю|ые|ых|их|х|ыми|ими|ми)(?!\p{L})((?:\s+\p{L}+)?)/gu,
    (m, num, end, next, offset, all) => {
      const n = Number(num);
      const noun = next.trim().toLowerCase();
      const prev = all.slice(0, offset).match(/(\p{L}+)\s*$/u)?.[1];
      let gender = 'm';
      let cs = 'nom';
      if (/^(ая|я)$/.test(end)) gender = 'f';
      else if (/^(ую|ю)$/.test(end)) ((gender = 'f'), (cs = 'acc'));
      else if (/^(ое|ее|е)$/.test(end))
        gender = /[ыи]$/.test(noun) ? 'p' : 'n'; // «3-е издание», «1-е места» (мн.)
      else if (/^(ого|его|го)$/.test(end)) cs = 'gen';
      else if (/^(ому|ему|му)$/.test(end)) cs = 'dat';
      else if (/^(ом|ем|м)$/.test(end))
        cs = /(ам|ям)$/.test(noun) ? ((gender = 'p'), 'dat') : 'prep'; // «на 2-м месте», «5-м классам»
      else if (/^(ым|им)$/.test(end)) cs = 'ins';
      else if (/^(ые)$/.test(end)) gender = 'p';
      else if (/^(ых|их|х)$/.test(end)) ((gender = 'p'), (cs = caseByPreposition(prev, 'gen') === 'prep' ? 'prep' : 'gen'));
      else if (/^(ыми|ими|ми)$/.test(end)) ((gender = 'p'), (cs = 'ins'));
      else if (end === 'ой' && /[ыиеу]$|ой$|ей$|ью$/.test(noun))
        ((gender = 'f'), (cs = caseByPreposition(prev, 'gen') === 'acc' ? 'gen' : caseByPreposition(prev, 'gen')));
      else if (end === 'й' && /[ыи]$/.test(noun))
        ((gender = 'f'), (cs = 'gen')); // «2-й главы»
      else if (end === 'й' && /(ой|ей)$/.test(noun)) ((gender = 'f'), (cs = 'ins'));
      else if (end === 'й' && /е$/.test(noun)) ((gender = 'f'), (cs = 'prep')); // «в 3-й главе»
      if (cs === 'nom' && /^(в|во|на|за|про|через)$/i.test(prev || '') && gender !== 'p') cs = 'acc'; // «в 3-й раз», «на 2-ю неделю»
      if (gender === 'm' && cs === 'acc') cs = 'nom';
      return `${ordinalWords(n, gender, cs)}${next}`;
    },
  );

  // Диапазон лет: «в 1905–1907 годах» → «в тысяча девятьсот пятом — тысяча девятьсот седьмом годах»,
  // «1905—1907 годов» → «…пятого — …седьмого годов»; без слова «годы» падеж — по предлогу
  const RANGE_WORD_CASE = { годы: 'nom', годов: 'gen', годах: 'prep', годам: 'dat', годами: 'ins' };
  t = t.replace(/(?:(\p{L}+)\s+)?(\d{3,4})\s*[-–—]\s*(\d{3,4})(?:\s*(годы|годов|годах|годам|годами|гг\.))?/gu, (m, prev, a, b, word) => {
    if (Number(b) < Number(a) || Number(a) < 100) return m;
    let cs = RANGE_WORD_CASE[word];
    // без слова «годы»: по предлогу; после существительного («война 1914–1918») — родительный; в начале фразы — именительный
    if (!cs) cs = prev ? { prep: 'prep', dat: 'dat', acc: 'nom', gen: 'gen' }[caseByPreposition(prev, 'gen')] || 'gen' : 'nom';
    const spoken = word === 'гг.' || !word ? { nom: 'годы', gen: 'годов', prep: 'годах', dat: 'годам', ins: 'годами' }[cs] : word;
    const range = `${ordinalWords(Number(a), 'm', cs)} — ${ordinalWords(Number(b), 'm', cs)}`;
    return `${prev ? `${prev} ` : ''}${range}${word || /^\d{4}$/.test(a) ? ` ${spoken}` : ''}`;
  });

  // «с 1905 по 1907 год» → «с тысяча девятьсот пятого по тысяча девятьсот седьмой год»
  t = t.replace(/(?<!\p{L})(с|со|от)\s+(\d{3,4})\s+(по|до)\s+(\d{3,4})\s+(год|года|годы|годов)(?!\p{L})/giu, (m, from, a, to, b, word) => {
    const second = to.toLowerCase() === 'по' ? 'nom' : 'gen';
    return `${from} ${ordinalWords(Number(a), 'm', 'gen')} ${to} ${ordinalWords(Number(b), 'm', second)} ${word}`;
  });

  // Годы: «в 1962 году» → «в тысяча девятьсот шестьдесят втором году», «1962 года» → «…втором… года» в род. падеже
  // Но «отмечает 323 года», «исполнилось 300 лет» — это количество лет, а не год: такие числа остаются
  // количественными («триста двадцать три года») и согласуются ниже как обычный счёт.
  t = t.replace(/(?:(\p{L}+)\s+)?(\d{3,4})\s+(год|года|году|годом|годе)(?!\p{L})/gu, (m, prev, y, word, offset, all) => {
    if (isYearCount(Number(y), word, prev, all.slice(offset + m.length))) return m;
    let cs = YEAR_WORD_CASE[word];
    if (word === 'году' && ['к', 'ко', 'по'].includes((prev || '').toLowerCase())) cs = 'dat';
    if (word === 'год' && prev) cs = caseByPreposition(prev, 'nom') === 'acc' ? 'acc' : 'nom';
    return `${prev ? `${prev} ` : ''}${ordinalWords(Number(y), 'm', cs)} ${word}`;
  });
  // «в 1962 г.» → как «году/года» по предлогу
  t = t.replace(/(?:(\p{L}+)\s+)?(\d{3,4})\s*г\.(?=\s|$|[,;])/gu, (m, prev, y) => {
    const cs = caseByPreposition(prev, 'gen');
    const word = { prep: 'году', dat: 'году', acc: 'год', gen: 'года' }[cs] || 'года';
    return `${prev ? `${prev} ` : ''}${ordinalWords(Number(y), 'm', cs === 'acc' ? 'acc' : cs)} ${word}`;
  });

  // Диапазон дат: «с 12 по 15 апреля» → «с двенадцатого по пятнадцатое апреля», «с 1 до 5 мая» → «с первого до пятого мая»
  t = t.replace(
    new RegExp(`(?<!\\p{L})(с|со|от)\\s+(\\d{1,2})\\s+(по|до)\\s+(\\d{1,2})\\s+(${MONTHS.join('|')})`, 'giu'),
    (m, from, a, to, b, mon) =>
      `${from} ${ordinalWords(Number(a), 'n', 'gen')} ${to} ${ordinalWords(Number(b), 'n', to.toLowerCase() === 'по' ? 'acc' : 'gen')} ${mon}`,
  );

  // Даты: «12 апреля» → «двенадцатого апреля»; «сегодня 26 сентября» → «двадцать шестое»; «по 15 апреля» → «по пятнадцатое»
  // Дата с годом без слова перед ней («…в космос, 12 апреля 1961 года») — это «когда»: двенадцатого апреля.
  // Но «сейчас воскресенье, 27 сентября 2026 года», «сегодня, 27 сентября», «5 октября 2026 года — понедельник» — «какое число»:
  // двадцать седьмое. «В воскресенье, 27 сентября» — снова «когда».
  const NOMINATIVE_BEFORE = [
    'сегодня',
    'завтра',
    'вчера',
    'послезавтра',
    'позавчера',
    'сейчас',
    'уже',
    'это',
    'было',
    'будет',
    'наступило',
    'наступит',
    'наступает',
  ];
  const WEEKDAY_NOM = /(?:(\p{L}+)\s+)?(понедельник|вторник|среда|четверг|пятница|суббота|воскресенье)\s*,\s*$/iu;
  t = t.replace(new RegExp(`(?:(\\p{L}+)\\s+)?(\\d{1,2})\\s+(${MONTHS.join('|')})`, 'gu'), (m, prev, d, mon, offset, all) => {
    const p = (prev || '').toLowerCase();
    const before = all.slice(0, offset);
    const after = all.slice(offset + m.length);
    // год к этому месту уже словами: «… тысяча девятьсот шестьдесят первого года»
    const yearRe = /^\s+(?:\d{4}\s*(?:года|г\.)|(?:\p{L}+\s+){0,4}\p{L}+(?:ого|его)\s+года)/u;
    const withYear = yearRe.test(after);
    // «27 сентября 2026 года — воскресенье»: дата — подлежащее, за ней тире
    const dashAfter = /^\s*[—–]\s/.test(after.replace(yearRe, ''));
    // «воскресенье, 27 сентября» (но не «в воскресенье, …»), «сегодня, 27 сентября»
    const weekday = !prev && before.match(WEEKDAY_NOM);
    const afterComma = !prev && before.match(/(\p{L}+)\s*,\s*$/u)?.[1]?.toLowerCase();
    const whenWeekday = weekday && /^(в|во|на|к|ко|до|с|со|по|после)$/i.test(weekday[1] || ''); // «во вторник, 29 сентября»
    const nominative =
      !whenWeekday &&
      ((!prev && (!withYear || dashAfter)) || NOMINATIVE_BEFORE.includes(p) || weekday || NOMINATIVE_BEFORE.includes(afterComma));
    const cs = nominative ? 'nom' : caseByPreposition(p, 'gen') === 'prep' ? 'gen' : caseByPreposition(p, 'gen');
    return `${prev ? `${prev} ` : ''}${ordinalWords(Number(d), 'n', cs)} ${mon}`;
  });

  // Сокращения в адресах и перед числом: «№ 5» → «номер 5», «ок. 5 км» → «около 5 км», «ул. Ленина», «см. выше»
  for (const [re, say] of ABBR_WORDS) t = t.replace(re, (m) => keepCase(m, say));

  // Дроби: «1/2» → «половина», «3/4» → «три четверти», «2/5» → «две пятых»; после «до/из/около…» — в родительном
  t = t.replace(/(?<![\d/.,])24\/7(?![\d/])/g, '24 на 7');
  t = t.replace(/(?<![\d/.,:\p{L}])(\d{1,2})\/(\d{1,2})(?![\d/])/gu, (m, a, b, offset, all) => {
    const x = Number(a);
    const y = Number(b);
    if (!x || y < 2 || y > 10 || x >= y) return m;
    const gen = GEN_PREPS.has(prevWord(all, offset));
    const SPECIAL = {
      '1/2': ['половина', 'половины'],
      '1/3': ['треть', 'трети'],
      '1/4': ['четверть', 'четверти'],
      '3/4': ['три четверти', 'трёх четвертей'],
    };
    if (SPECIAL[`${x}/${y}`]) return SPECIAL[`${x}/${y}`][gen ? 1 : 0];
    const whole = numberToWords(x, 'f');
    if (x === 1) return `${gen ? 'одной' : 'одна'} ${ordWord(y, 'f', gen ? 'gen' : 'nom')}`;
    return `${gen ? toGenitive(whole) : whole} ${ordWord(y, 'p', 'gen')}`;
  });

  // Выражения с «=»: «2 + 2 = 4» → «два плюс два равно четыре», «2^10» → «два в степени десять»
  if (/[\d\p{L})]\s*=\s*[-−]?[\d(]/u.test(t)) {
    const OPS = {
      '+': 'плюс',
      '-': 'минус',
      '−': 'минус',
      '×': 'умножить на',
      '*': 'умножить на',
      '·': 'умножить на',
      '÷': 'разделить на',
      '/': 'разделить на',
      '^': 'в степени',
      '=': 'равно',
    };
    t = t.replace(/(?<=[\d)\p{L}])\s*([+×*·÷/^=]|\s[-−]\s)\s*(?=[-−]?[\d(])/gu, (m, op) => ` ${OPS[op.trim()]} `);
  }

  // Размеры: «5×3», «1920x1080» → «пять на три»
  t = t.replace(/(\d)\s*[×xх]\s*(?=\d)/g, '$1 на ');

  // «сутки» — только множественное: «одни сутки», «двое суток», «пять суток»
  t = t.replace(/(?<![\d.,])(\d+)(\s+)(сутки|суток)(?!\p{L})/gu, (m, num, sp) => {
    const n = Number(num);
    if (n % 10 === 1 && n % 100 !== 11) return `${n > 1 ? `${numberToWords(n - 1)} ` : ''}одни${sp}сутки`; // 21 → «двадцать» + «одни»
    if (n >= 2 && n <= 4) return ['двое', 'трое', 'четверо'][n - 2] + sp + 'суток';
    return m;
  });

  // Время: «10:30» → «десять тридцать», «9:05» → «девять ноль пять», «7:00» → «семь часов»;
  // после «с/до/около…» — родительный («с девяти до восемнадцати тридцати»), после «к» — дательный
  t = t.replace(/(?<![\d:])([01]?\d|2[0-3]):([0-5]\d)(?![\d:])/g, (m, h, mi, offset, all) => {
    const prev = prevWord(all, offset);
    const n = Number(h);
    const one = n % 10 === 1 && n % 100 !== 11;
    // ровный час — числом и словом «час»: дальше их согласуют общие правила
    if (mi === '00') {
      if (GEN_PREPS.has(prev)) return `${h} ${one ? 'часа' : 'часов'}`;
      if (/^(к|ко)$/.test(prev)) return `${h} ${one ? 'часу' : 'часам'}`;
      return `${h} ${plural(n, ['час', 'часа', 'часов'])}`;
    }
    const words = `${numberToWords(n)} ${mi.startsWith('0') ? `ноль ${numberToWords(Number(mi[1]))}` : numberToWords(Number(mi))}`;
    if (GEN_PREPS.has(prev)) return toGenitive(words);
    if (/^(к|ко)$/.test(prev)) return toDative(words);
    return words;
  });
  // Счёт и соотношение: «3:1» → «три — один», «соотношение 16:9» → «шестнадцать на девять»
  t = t.replace(/(?<![\d:])(\d+):(\d+)(?![\d:])/g, (m, a, b, offset, all) =>
    /(соотношени|формат|пропорци|масштаб)\p{L}*\s*$/iu.test(all.slice(0, offset)) ? `${a} на ${b}` : `${a} — ${b}`,
  );

  // $84 → «84 $», «$19.99» → «19.99 $», «€10» → «10 €»
  t = t.replace(/([$€])\s?(\d+(?:[.,]\d+)?)(?!\d)/g, '$2 $1');

  // Деньги с копейками и центами: «84,34 рубля» → «восемьдесят четыре рубля тридцать четыре копейки»,
  // «101,5 рубля» → «сто один рубль пятьдесят копеек», «19.99 $» → «девятнадцать долларов девяносто девять центов»
  t = t.replace(/(\d+)[,.](\d{1,2})(?!\d)\s*(рубл\p{L}*|руб\.?(?!\p{L})|₽|\$|доллар\p{L}*|€|евро(?!\p{L}))/gu, (m, a, b, cur) => {
    const money = /^(\$|доллар)/.test(cur) ? MONEY.usd : /^(€|евро)/.test(cur) ? MONEY.eur : MONEY.rub;
    const whole = Number(a);
    const cents = b.length === 1 ? Number(b) * 10 : Number(b);
    const main = `${numberToWords(whole)} ${plural(whole, money.main)}`;
    return cents ? `${main} ${numberToWords(cents, money.gender)} ${plural(cents, money.cents)}` : main;
  });

  // Знак перед числом: +13 → «плюс 13», −3 → «минус 3»
  t = t.replace(/(^|[\s(])\+(\d)/g, '$1плюс $2').replace(/(^|[\s(])[-−–](\d)/g, '$1минус $2');

  // Число + единица-символ: «13°», «85%», «2 м/с»; после «до/из/около…» — в родительном: «из 512 гигабайт»
  for (const [re, forms] of UNITS) {
    t = t.replace(new RegExp(`(\\d+(?:[.,]\\d+)?)\\s*(?:${re.source})`, 'gu'), (m, num, offset, all) => {
      if (/[.,]/.test(num)) return `${num} ${forms[1]}`; // дробное: «1,5 градуса»
      const n = Number(num);
      const prev = all.slice(0, offset).match(/(\p{L}+)\s+(?:(?:плюс|минус)\s+)?$/u)?.[1];
      if (prev && GENITIVE_BEFORE.test(prev)) return `${num} ${n % 10 === 1 && n % 100 !== 11 ? forms[1] : forms[2]}`;
      return `${num} ${plural(n, forms)}`;
    });
  }

  // Половины: «1,5 часа» → «полтора часа», «2,5 минуты» → «две с половиной минуты», «до 1,5 часов» → «до полутора часов»
  t = t.replace(/(?<![\d.,])(\d+)[,.]5(?![\d.,]\d|\d)(\s+)(\p{L}+)/gu, (m, a, sp, noun, offset, all) => {
    if (a === '0' || /^(и|или|а|но|на|в|до|от|по|с|из|к)$/i.test(noun)) return m;
    const gen = GEN_PREPS.has(prevWord(all, offset));
    const fem = /[ыи]$/i.test(noun); // «минуты», «недели», «тысячи»
    if (a === '1') return `${gen ? 'полутора' : fem ? 'полторы' : 'полтора'}${sp}${noun}`;
    const words = numberToWords(Number(a), fem ? 'f' : 'm');
    return `${gen ? toGenitive(words) : words} с половиной${sp}${noun}`;
  });

  // Диапазоны: «2-3 минуты» → «две-три минуты», «10–15 минут», «от 2-3 дней» → «от двух-трёх дней» (через дефис — без паузы)
  t = t.replace(/(?<![\d.,:\p{L}-])(\d+)\s*[-–—]\s*(\d+)(?![\d.,:-])((?:\s+\p{L}+)?)/gu, (m, a, b, noun, offset, all) => {
    const x = Number(a);
    const y = Number(b);
    if (y <= x) return m;
    const next = noun.trim();
    const gen = GEN_PREPS.has(prevWord(all, offset));
    const gender =
      [1, 2].includes(y % 10) && y % 100 !== 11 && y % 100 !== 12
        ? gen
          ? genderOfGenitive(next, y)
          : genderOf(next, y)
        : /[ыи]$/i.test(next)
          ? 'f'
          : 'm';
    const say = (n) => (gen ? toGenitive(numberToWords(n, gender)) : numberToWords(n, gender));
    return `${say(x)}-${say(y)}${noun}`;
  });

  // Дательный: «к 5 часам» → «к пяти часам», «к 1 минуте» → «к одной минуте»; «по 1 штуке» → «по одной штуке»
  t = t.replace(/(?<!\p{L})(к|ко)(\s+)(\d+)(?![\d:]|[.,]\d)((?:\s+\p{L}+)?)/giu, (m, prep, sp, num, noun) => {
    const n = Number(num);
    const fem = n % 10 === 1 && n % 100 !== 11 && /[еи]$/i.test(noun.trim());
    return `${prep}${sp}${toDative(numberToWords(n, fem ? 'f' : 'm'))}${noun}`;
  });
  t = t.replace(/(?<!\p{L})(по)(\s+)(\d*1)(?![\d:]|[.,]\d)(\s+)(\p{L}+[еую])(?!\p{L})/giu, (m, prep, sp, num, sp2, noun) => {
    const n = Number(num);
    if (n % 100 === 11) return m;
    return `${prep}${sp}${toDative(numberToWords(n, /е$/i.test(noun) ? 'f' : 'm'))}${sp2}${noun}`;
  });

  // Количественные после «до/от/около/с…» — в родительном падеже: «до плюс 16» → «до плюс шестнадцати»;
  // «с 5 друзьями» — в творительном: «с пятью друзьями». Следующее слово — существительное, если это не предлог/союз.
  t = t.replace(
    /(?<!\p{L})(до|от|около|более|менее|свыше|из|без|после|с|со|у|для|кроме)(\s+)((?:плюс|минус)\s+)?(\d+)(?![\d:]|[.,]\d)((?:\s+(?!(?:до|от|по|и|или|а|с|со|в|на)(?!\p{L}))\p{L}+)?)/giu,
    (m, prep, sp, sign, num, noun) => {
      const n = Number(num);
      const next = noun.trim();
      const instrumental = /^(с|со)$/i.test(prep) && /(ами|ями|ьми|ом|ем|ой|ей|ью)$/i.test(next);
      const base = numberToWords(n, instrumental ? genderOf(next, n) : genderOfGenitive(next, n));
      return `${prep}${sp}${sign || ''}${instrumental ? toInstrumental(base) : toGenitive(base)}${noun}`;
    },
  );

  // Дробные: 1,48 → «одна целая сорок восемь сотых»
  t = t.replace(/(\d+)[,.](\d+)/g, (m, a, b) => decimalToWords(a, b));

  // Целые с согласованием по следующему слову: «1 минута» → «одна минута», «2 недели» → «две недели»
  // (число в конце фразы или перед запятой тоже превращается в слова)
  t = t.replace(/(\d+)(?:(\s+)(\p{L}+))?/gu, (m, num, space, noun) => {
    const n = Number(num);
    const words = numberToWords(n, genderOf(noun, n));
    return noun ? `${words}${space}${noun}` : words;
  });

  for (const [re, say] of SAY_AS) t = t.replace(re, say);
  t = spellLatinAbbreviations(t);
  t = spellCyrillicAbbreviations(t);
  return eyo
    .restore(t)
    .replace(/\s{2,}/g, ' ')
    .trim();
}

module.exports = { normalizeForSpeech, numberToWords, decimalToWords, ordinal, ordinalWords, genderOf };
