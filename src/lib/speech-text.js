const CENTURY_CASE = { век: 'nom', века: 'gen', веке: 'prep', веку: 'dat', веком: 'ins', веков: 'gen', веках: 'prep', векам: 'dat' };

function romanNumerals(t) {
  // Века: «XIX век», «в XIX в.», «XVIII–XIX веков», «в XVIII—XIX вв.»
  t = t.replace(
    /(?:(\p{L}+)\s+)?([IVXLC]{1,7})(?:\s*[-–—]\s*([IVXLC]{1,7}))?\s*(век|века|веке|веку|веком|веков|веках|векам|вв\.|в\.)(?!\p{L})/gu,
    (m, prev, a, b, word, offset, all) => {
      const x = romanValue(a);
      const y = b ? romanValue(b) : null;
      if (!x || (b && !y)) return m;
      let cs = CENTURY_CASE[word];
      let spoken = word;
      if (!cs) {
        // сокращение: падеж по предлогу («в XIX в.» → «в девятнадцатом веке», «до XV в.» → «до пятнадцатого века»)
        const byPrep = caseByPreposition(prev, 'nom');
        cs = byPrep === 'acc' ? 'nom' : byPrep;
        spoken = y
          ? { nom: 'века', gen: 'веков', prep: 'веках', dat: 'векам', ins: 'веками' }[cs]
          : { nom: 'век', gen: 'века', prep: 'веке', dat: 'веку', ins: 'веком' }[cs];
      }
      const lead = prev ? `${prev} ` : '';
      // «…в XIX в.» в конце предложения: точка сокращения — это и конец предложения
      const end = word.endsWith('.') && /^(\s*$|\s+[А-ЯЁA-Z])/.test(all.slice(offset + m.length)) ? '.' : '';
      return `${lead}${ordinalWords(x, 'm', cs)}${y ? ` — ${ordinalWords(y, 'm', cs)}` : ''} ${spoken}${end}`;
    },
  );
  // Правители и нумерованные части: «Петра I», «Екатерина II», «глава IV»
  t = t.replace(/(?<!\p{L})(\p{L}+)\s+([IVXLC]{1,7})(?![\p{L}\d])/gu, (m, word, r) => {
    const n = romanValue(r);
    if (!n) return m;
    const numbered = NUMBERED[word.toLowerCase()];
    if (numbered) return `${word} ${ordinalWords(n, numbered, 'nom')}`;
    if (!/^[А-ЯЁ][а-яё]+$/.test(word)) return m; // имя правителя — с заглавной, по-русски
    const [gender, cs] = rulerForm(word);
    return `${word} ${ordinalWords(n, gender, cs)}`;
  });
  return t;
}

function isYearCount(n, word, prev, after) {
  if (!['год', 'года'].includes(word) || plural(n, ['год', 'года', 'лет']) !== word) return false;
  if (/^\s*(до\s+)?(н\.\s?э|нашей эры)/i.test(after)) return false;
  const p = (prev || '').toLowerCase();
  if (COUNT_BEFORE.test(p)) return true;
  return n < 1000 && !DATE_PREPOSITION.test(p);
}

