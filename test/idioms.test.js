test('жалобы не меняют систему не туда: «темно» — ярче, а не выключить экран; «тормозит» — проверка, а не питание', () => {
  const { skills } = makeRegistry();
  assert.equal(plan(skills, 'ничего не видно на экране темно'), 'brightness(+20)');
  assert.equal(plan(skills, 'экран слишком яркий'), 'brightness(-20)');
  assert.equal(plan(skills, 'компьютер медленно работает'), 'pc_status(процессы)');
  assert.equal(plan(skills, 'как выключить компьютер'), 'power(shutdown 1)', 'навык питания ещё переспросит');
  // Не про то, чем кажется
  assert.equal(plan(skills, 'что я купил вчера'), null, '«что … купил» — вопрос, не вычеркнуть');
  assert.notEqual(plan(skills, 'пятнадцать процентов от тысячи'), 'volume(15)');
  assert.equal(plan(skills, 'как работает вай фай'), null, 'вопрос, а не выключить Wi-Fi');
});

test('числа словами, время, калькулятор', () => {
  assert.equal(wordsToNumber('две тысячи'), 2000);
  assert.equal(wordsToNumber('тысяча двести'), 1200);
  assert.equal(wordsToNumber('от двух тысяч'), 2000);
  assert.equal(calcExpr('двадцать пять процентов от двух тысяч'), '2000 * 25%');
  assert.equal(calcExpr('сколько будет двести на три'), '200 * 3');
  assert.equal(calcExpr('сколько будет абв'), null);
  assert.deepEqual(parseClock('разбуди в полседьмого'), { h: 6, m: 30 });
  assert.equal(fromText('remind_at', 'напомни мне вечером в девять принять лекарство'), '21:00|принять лекарство');
  assert.equal(fromText('weather', 'погода в питере'), 'питере|сегодня', 'распознавание пишет строчными — город всё равно найден');
});
