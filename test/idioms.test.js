// Как говорит человек без опыта с компьютером: вежливые обёртки, вопрос «как сделать», жалобы, сокращения,
// порядок слов — быстрый разбор понимает это без модели (lib/idioms.js + разбор навыков)
const { makeRegistry } = require('./helpers');
const test = require('node:test');
const assert = require('node:assert/strict');
const { normalizeRequest } = require('../src/lib/idioms');
const { calcExpr, fromText } = require('../src/lib/text-args');
const { wordsToNumber } = require('../src/lib/ru');
const { parseClock } = require('../src/lib/clock');

const plan = (skills, text) =>
  skills
    .quickPlan(text)
    ?.actions?.map((a) => `${a.tool}(${a.arg})`)
    .join(' ') ?? null;

test('просьба → команда: вежливость, «как сделать», сокращения, глагол в конце', () => {
  const cases = {
    'а можешь включить музыку': 'включи музыку',
    'ну это самое включи песню пугачёвой': 'включи песню пугачевой',
    'не могла бы ты поставить будильник на семь': 'поставь будильник на семь',
    'как выключить компьютер': 'выключи компьютер',
    'блютуз включи': 'включи блютуз',
    'хочу музыку': 'включи музыку',
    'радио маяк хочу': 'включи радио маяк',
    'вкл радио': 'включи радио',
    'врубай блютус': 'включи блютус',
    'включи ка радио': 'включи радио',
    'включи пожалуйста радио маяк а то скучно': 'включи радио маяк',
    'мне завтра вставать в шесть': 'разбуди меня завтра в шесть',
    'сколько времени сейчас': 'который час',
    'как будет по немецки спасибо': 'как будет по немецки спасибо', // «спасибо» здесь — слово для перевода
  };
  for (const [said, command] of Object.entries(cases)) assert.equal(normalizeRequest(said), command, said);
});

